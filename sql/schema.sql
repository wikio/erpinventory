CREATE TABLE `tax_records` (`id` VARCHAR(64) PRIMARY KEY, `reference_code` VARCHAR(150) UNIQUE, `type` VARCHAR(20), `period` VARCHAR(20), `status` VARCHAR(32), `taxable_revenue` DECIMAL(18,2), `vat_collected` DECIMAL(18,2), `vat_deductible` DECIMAL(18,2), `amount_due` DECIMAL(18,2));
CREATE TABLE `g50_payments` (`id` VARCHAR(64) PRIMARY KEY, `tax_record_id` VARCHAR(64) NOT NULL, `amount` DECIMAL(18,2), `payment_date` DATE, `method` VARCHAR(50), `bank_account_id` VARCHAR(64), FOREIGN KEY (`tax_record_id`) REFERENCES `tax_records` (`id`));

